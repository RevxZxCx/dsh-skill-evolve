// Regenerate the list of CSS custom properties the host theme actually defines.
//
// Run this after a host upgrade:
//   node scripts/extract-host-tokens.mjs
//
// It reads the theme's client bundle out of the running app and writes
// test/host-tokens.txt, which test/tokens.test.mjs compares against the token names
// lib/client.js references. Everything the panel styles is a CSS variable; a name the
// host does not define silently falls back to the hard-coded colour next to it, which
// is invisible in one theme and wrong in the other. That is exactly what shipped once
// (four invented names, all of them looking plausible in light mode), so the check is
// a real regression guard rather than a style rule.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const repo = fileURLToPath(new URL('..', import.meta.url))

// The theme lives inside the packaged app, so it is read from the asar by hand
// rather than through node_modules (the desktop profile links packages, but the
// theme is a built client asset that only exists in the archive).
const ASAR = process.env.DSH_ASAR ?? 'F:/DSH/resources/app.asar'
const THEME = 'dsh/node_modules/@deepseek-ai/dsh-client-ui-theme/lib/client.js'

function readFromAsar(archive, member) {
  const fd = readFileSync(archive) // small enough to load whole; keeps the walk simple
  const headerSize = fd.readUInt32LE(12)
  const header = JSON.parse(fd.subarray(16, 16 + headerSize).toString('utf8').replace(/\0+$/, ''))
  const base = 16 + headerSize
  let node = header
  for (const part of member.split('/')) {
    const next = node.files?.[part]
    if (next === undefined) throw new Error(`asar member not found: ${member} (at ${part})`)
    node = next
  }
  if (node.files !== undefined) throw new Error(`asar member is a directory: ${member}`)
  return fd.subarray(base + Number(node.offset), base + Number(node.offset) + Number(node.size)).toString('utf8')
}

const theme = readFromAsar(ASAR, THEME)

// Two ways a token reaches the document: a `--dsw-x:` declaration in the stylesheet,
// or a `setProperty('--dsw-x', ...)` call for values computed at runtime.
const defined = new Set()
for (const match of theme.matchAll(/(--dsw-[a-z0-9-]+)\s*:/g)) defined.add(match[1])
for (const match of theme.matchAll(/setProperty\(\s*['"](--dsw-[a-z0-9-]+)/g)) defined.add(match[1])

const names = [...defined].sort()
if (names.length < 100) throw new Error(`only ${names.length} tokens found; the theme moved or changed shape`)

const target = path.join(repo, 'test', 'host-tokens.txt')
const body = [
  '# CSS custom properties the host theme defines.',
  '# Generated by scripts/extract-host-tokens.mjs -- do not edit by hand.',
  `# Source: ${THEME}`,
  `# Tokens: ${names.length}`,
  '',
  ...names,
].join('\n')
writeFileSync(target, `${body}\n`)
console.log(`wrote ${target} with ${names.length} tokens`)
