#!/usr/bin/env node
/**
 * Builds deterministic active views from sharded handover entries and task cards:
 *   - docs/handover/ACTIVE-STATE.md
 *   - docs/handover/ACTIVE-DECISIONS.md
 *
 * Usage:
 *   node scripts/build-handover-views.mjs          # write views (LF line endings)
 *   node scripts/build-handover-views.mjs --check  # exit 1 if views are missing or stale
 */

import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const entriesDir = join(root, 'docs', 'handover', 'entries')
const tasksDir = join(root, 'docs', 'tasks')
const stateOut = join(root, 'docs', 'handover', 'ACTIVE-STATE.md')
const decisionsOut = join(root, 'docs', 'handover', 'ACTIVE-DECISIONS.md')

const checkOnly = process.argv.includes('--check')

function parseFrontmatter(raw) {
  const normalized = raw.replace(/\r\n/g, '\n')
  const match = normalized.match(/^---\n([\s\S]*?)\n---\n?([\s\S]*)$/)
  if (!match) return { meta: {}, body: normalized.trim() }
  const meta = {}
  let currentListKey = null
  for (const line of match[1].split('\n')) {
    const listItem = line.match(/^\s+-\s+(.*)$/)
    if (listItem && currentListKey) {
      meta[currentListKey].push(stripQuotes(listItem[1].trim()))
      continue
    }
    const kv = line.match(/^([A-Za-z0-9_-]+):\s*(.*)$/)
    if (!kv) {
      currentListKey = null
      continue
    }
    const key = kv[1]
    const val = kv[2].replace(/\s+#.*$/, '').trim()
    if (val === '') {
      meta[key] = []
      currentListKey = key
    } else if (val.startsWith('[') && val.endsWith(']')) {
      meta[key] = val
        .slice(1, -1)
        .split(',')
        .map((s) => stripQuotes(s.trim()))
        .filter(Boolean)
      currentListKey = null
    } else {
      meta[key] = stripQuotes(val)
      currentListKey = null
    }
  }
  return { meta, body: match[2].trim() }
}

function stripQuotes(s) {
  if ((s.startsWith('"') && s.endsWith('"')) || (s.startsWith("'") && s.endsWith("'"))) {
    return s.slice(1, -1)
  }
  return s
}

function loadMarkdownDir(dir, exclude) {
  if (!existsSync(dir)) return []
  return readdirSync(dir)
    .filter((name) => name.endsWith('.md') && !exclude.has(name))
    .sort()
    .map((file) => {
      const fullPath = join(dir, file)
      const { meta, body } = parseFrontmatter(readFileSync(fullPath, 'utf8'))
      return { file, meta, body }
    })
}

function escapeCell(value) {
  return String(value ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ')
}

const entries = loadMarkdownDir(entriesDir, new Set(['README.md']))
  .sort((a, b) => {
    const da = String(a.meta.date ?? '')
    const db = String(b.meta.date ?? '')
    if (da !== db) return db.localeCompare(da)
    return b.file.localeCompare(a.file)
  })

const tasks = loadMarkdownDir(tasksDir, new Set(['README.md', '_template.md']))
  .filter((t) => t.meta.status !== 'done')
  .sort((a, b) => String(b.meta.updated ?? '').localeCompare(String(a.meta.updated ?? '')))

const latestStatus = entries.find((e) => e.meta.type === 'status')
const pendingVerifications = entries.filter(
  (e) => e.meta.status === 'pending_live_verify' || (typeof e.meta.pending_verify === 'string' && e.meta.pending_verify.length > 0),
)

const stateLines = [
  '<!-- AUTO-GENERATED by scripts/build-handover-views.mjs — DO NOT EDIT BY HAND -->',
  '# 活跃交接视图（ACTIVE-STATE）',
  '',
  '> 本文件由 `npm run handover:build` 从 `docs/handover/entries/` 与 `docs/tasks/` 自动生成，用于新 Agent **10 秒内完成冷启动接手**。历史流水见冻结台账 [`01-status.md`](./01-status.md) – [`04-reviews.md`](./04-reviews.md)。',
  '',
  '## 1. 最新基线',
  '',
]

if (latestStatus) {
  stateLines.push(`- **最近状态条目**：[\`${latestStatus.file}\`](./entries/${latestStatus.file})（${latestStatus.meta.date ?? 'unknown'}）`)
  stateLines.push(`- **摘要**：${latestStatus.meta.title ?? '(untitled)'}`)
  if (latestStatus.meta.baseline) {
    stateLines.push(`- **记录基线**：${latestStatus.meta.baseline}`)
  }
} else {
  stateLines.push('- 暂无分片状态条目，请以 `npm run gate:fast` 实测结果为准。')
}

stateLines.push('', '## 2. 进行中任务（`docs/tasks/`）', '')
if (tasks.length === 0) {
  stateLines.push('当前无进行中任务单。新建多 Agent 任务请复制 [`docs/tasks/_template.md`](../tasks/_template.md)。')
} else {
  stateLines.push('| 任务单 | 状态 | 阶段 | 负责人 | 标题 |')
  stateLines.push('| --- | --- | --- | --- | --- |')
  for (const t of tasks) {
    stateLines.push(
      `| [\`${t.file}\`](../tasks/${t.file}) | ${escapeCell(t.meta.status)} | ${escapeCell(t.meta.stage)} | ${escapeCell(t.meta.owner)} | ${escapeCell(t.meta.title)} |`,
    )
  }
}

stateLines.push('', '## 3. 待闭环真机验收 / 阻塞项', '')
if (pendingVerifications.length === 0) {
  stateLines.push('当前无登记的待闭环真机验收项。')
} else {
  for (const e of pendingVerifications) {
    const note = e.meta.pending_verify || e.meta.title
    stateLines.push(`- **${e.meta.date ?? ''}** [\`${e.file}\`](./entries/${e.file})：${note}`)
  }
}

stateLines.push('', '## 4. 最近分片记录（最多 15 条）', '')
if (entries.length === 0) {
  stateLines.push('暂无分片记录。')
} else {
  stateLines.push('| 日期 | 类型 | 编号/状态 | 标题 | 文件 |')
  stateLines.push('| --- | --- | --- | --- | --- |')
  for (const e of entries.slice(0, 15)) {
    const badge = [e.meta.id, e.meta.status].filter(Boolean).join(' / ')
    stateLines.push(
      `| ${escapeCell(e.meta.date)} | ${escapeCell(e.meta.type)} | ${escapeCell(badge)} | ${escapeCell(e.meta.title)} | [\`${e.file}\`](./entries/${e.file}) |`,
    )
  }
}

stateLines.push('', '## 5. 历史台账（已冻结，只读）', '')
stateLines.push('- [`01-status.md`](./01-status.md)（2026-10-30 – 2026-11-25）')
stateLines.push('- [`02-decisions.md`](./02-decisions.md)（D-01 – D-254+）')
stateLines.push('- [`03-defects.md`](./03-defects.md)（DEF-01 – DEF-209）')
stateLines.push('- [`04-reviews.md`](./04-reviews.md)（R-01 – R-123+）')
stateLines.push('')

const decisions = entries.filter((e) => e.meta.type === 'decision')
const activeDecisions = decisions.filter((e) => e.meta.status !== 'superseded')
const supersededDecisions = decisions.filter((e) => e.meta.status === 'superseded')

const decisionLines = [
  '<!-- AUTO-GENERATED by scripts/build-handover-views.mjs — DO NOT EDIT BY HAND -->',
  '# 当前生效架构决策（ACTIVE-DECISIONS）',
  '',
  '> 本文件由 `npm run handover:build` 自动生成，仅汇总分片目录 `docs/handover/entries/` 中的架构决策。2026-11-25 之前的历史 ADR 冻结在 [`02-decisions.md`](./02-decisions.md)。',
  '',
  '## 生效中（Active）',
  '',
]

if (activeDecisions.length === 0) {
  decisionLines.push('暂无新增分片决策。')
} else {
  decisionLines.push('| 编号 | 日期 | 影响范围 | 决策 | 文件 |')
  decisionLines.push('| --- | --- | --- | --- | --- |')
  for (const d of activeDecisions) {
    const pkgs = Array.isArray(d.meta.packages) ? d.meta.packages.join(', ') : (d.meta.packages ?? 'repo')
    decisionLines.push(
      `| ${escapeCell(d.meta.id)} | ${escapeCell(d.meta.date)} | ${escapeCell(pkgs)} | ${escapeCell(d.meta.title)} | [\`${d.file}\`](./entries/${d.file}) |`,
    )
  }
}

if (supersededDecisions.length > 0) {
  decisionLines.push('', '## 已取代（Superseded）', '')
  decisionLines.push('| 编号 | 日期 | 取代者 | 原决策 | 文件 |')
  decisionLines.push('| --- | --- | --- | --- | --- |')
  for (const d of supersededDecisions) {
    decisionLines.push(
      `| ${escapeCell(d.meta.id)} | ${escapeCell(d.meta.date)} | ${escapeCell(d.meta.superseded_by ?? '-')} | ${escapeCell(d.meta.title)} | [\`${d.file}\`](./entries/${d.file}) |`,
    )
  }
}

decisionLines.push('')

const outputs = [
  { path: stateOut, label: 'docs/handover/ACTIVE-STATE.md', content: stateLines.join('\n') },
  { path: decisionsOut, label: 'docs/handover/ACTIVE-DECISIONS.md', content: decisionLines.join('\n') },
]

if (checkOnly) {
  let stale = false
  for (const out of outputs) {
    const current = existsSync(out.path) ? readFileSync(out.path, 'utf8').replace(/\r\n/g, '\n') : null
    if (current !== out.content) {
      console.error(`STALE ${out.label} — run \`npm run handover:build\``)
      stale = true
    } else {
      console.log(`ok   ${out.label}`)
    }
  }
  process.exit(stale ? 1 : 0)
}

for (const out of outputs) {
  writeFileSync(out.path, out.content, 'utf8')
  console.log(`wrote ${out.label}`)
}
